/** The jest full names of the cases the canary requires to die without the model's scope. */
export function isolationCaseNames(n: IModuleNames): { mustFail: string[]; describe: string } {
  const describe = `${n.dir} tenant isolation (generated)`;
  return {
    describe,
    mustFail: [
      `${describe} I1 a list under tenant B never returns a row of tenant A`,
      `${describe} I2 a get of a tenant A id under tenant B is NOT_FOUND`,
      `${describe} I3 an update of a tenant A id under tenant B is refused and changes nothing`,
      `${describe} I5 fails closed with no tenant in context`,
    ],
  };
}

export function isolationSpec(n: IModuleNames): string {
  const { describe } = isolationCaseNames(n);
  return `/**
 * ${n.model} tenant isolation, generated by \`pnpm new:module\` together with
 * the module it proves.
 *
 * Runs against the LIVE Postgres through the isolation lane
 * (\`pnpm --filter @repo/api test:integration\`), with the service built on the
 * real tenant-scope extension. It is built through the canary seam, so
 * \`pnpm canary:isolation\` can drop \`${n.accessor}\` from the registry and
 * require I1, I2, I3 and I5 to go red; the \`control:\` case must stay green.
 *
 * I4 is the other half of the boundary: a client-supplied tenantId must not
 * place a row in another organization. The router's zod schema strips the key; this
 * case proves the service would ignore it even if it arrived.
 *
 * A removed member's live session is refused at the session layer, not here:
 * see membership-lock.isolation.spec.ts.
 */
import { randomUUID } from 'node:crypto';
import type { PrismaClient } from '@repo/database' with { 'resolution-mode': 'import' };
import { AppErrorCode } from '@repo/shared/errors';
import type { ${n.model}CreateInput } from '@repo/shared/schemas';
import { buildCanaryTenantScopeExtension } from '@test/tenant-scope-canary';
import { expectRejectsDomainError } from '@test/domain-error-matchers';
import { esmImport } from '../../common/utils/esm-import';
import { requestContext } from '../../common/context/request-context';
import { NotFoundError } from '../../common/errors/domain-error';
import type { PrismaService } from '../../common/database/prisma.service';
import type { AuditService } from '../audit/audit.service';
import { ${n.model}Repository } from './${n.kebab}.repository';
import { ${n.model}Service } from './${n.kebab}.service';

const NO_SUCH_ROW = {
  type: NotFoundError,
  appCode: AppErrorCode.NOT_FOUND,
  message: '${n.model} not found.',
} as const;

let unscoped: PrismaClient;
let service: ${n.model}Service;
let tenantA: { id: string };
let tenantB: { id: string };
let rowA: { id: string; name: string };
const createdTenantIds: string[] = [];

/** The \`await fn()\` keeps the lazy Prisma promise inside the tenant scope. */
const run = <T>(tenantId: string | undefined, fn: () => Promise<T>): Promise<T> =>
  requestContext.run({ requestId: '${n.dir}-iso', tenantId }, async () => await fn());

beforeAll(async () => {
  const { prisma } = (await esmImport('@repo/database')) as { prisma: PrismaClient };
  unscoped = prisma;
  const client = unscoped.$extends(buildCanaryTenantScopeExtension()) as unknown as PrismaClient;
  const audit = { log: jest.fn().mockResolvedValue(undefined) } as unknown as AuditService;
  service = new ${n.model}Service(
    new ${n.model}Repository({ client, unscoped } as unknown as PrismaService),
    audit,
  );

  const uid = randomUUID();
  tenantA = await unscoped.tenant.create({ data: { name: \`${n.kebab}-a-\${uid}\`, slug: \`${n.kebab}-a-\${uid}\` } });
  tenantB = await unscoped.tenant.create({ data: { name: \`${n.kebab}-b-\${uid}\`, slug: \`${n.kebab}-b-\${uid}\` } });
  createdTenantIds.push(tenantA.id, tenantB.id);
  rowA = await unscoped.${n.accessor}.create({
    data: { tenantId: tenantA.id, name: \`${n.kebab}-row-a-\${uid}\` },
  });
});

afterAll(async () => {
  await unscoped.${n.accessor}.deleteMany({ where: { tenantId: { in: createdTenantIds } } });
  await unscoped.tenant.deleteMany({ where: { id: { in: createdTenantIds } } });
  await unscoped?.$disconnect();
});

describe('${describe}', () => {
  it('control: tenant A lists and reads its own row', async () => {
    const listed = await run(tenantA.id, () => service.list());
    expect(listed.items.map((item) => item.id)).toContain(rowA.id);
    await expect(run(tenantA.id, () => service.get({ id: rowA.id }))).resolves.toMatchObject({
      id: rowA.id,
    });
  });

  it('I1 a list under tenant B never returns a row of tenant A', async () => {
    const listed = await run(tenantB.id, () => service.list());
    expect(listed.items.map((item) => item.id)).not.toContain(rowA.id);
  });

  it('I2 a get of a tenant A id under tenant B is NOT_FOUND', async () => {
    await expectRejectsDomainError(
      run(tenantB.id, () => service.get({ id: rowA.id })),
      NO_SUCH_ROW,
    );
  });

  it('I3 an update of a tenant A id under tenant B is refused and changes nothing', async () => {
    await expectRejectsDomainError(
      run(tenantB.id, () => service.update({ id: rowA.id, name: 'przejete' })),
      NO_SUCH_ROW,
    );
    const stored = await unscoped.${n.accessor}.findUnique({ where: { id: rowA.id } });
    expect(stored?.name).toBe(rowA.name);
  });

  it('I4 a client-supplied tenantId cannot place a row in another tenant', async () => {
    const smuggled = { name: 'przemycony', tenantId: tenantB.id } as unknown as ${n.model}CreateInput;
    const created = await run(tenantA.id, () => service.create(smuggled));
    const stored = await unscoped.${n.accessor}.findUnique({ where: { id: created.id } });
    expect(stored?.tenantId).toBe(tenantA.id);
  });

  it('I5 fails closed with no tenant in context', async () => {
    await expect(run(undefined, () => service.list())).rejects.toThrow();
  });
});
`;
}
