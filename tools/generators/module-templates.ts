/*
 * The files `pnpm new:module` creates, as pure functions of the names.
 *
 * Each template is the smallest module that passes every guard a hand-written
 * one must pass: class-level AuthMiddleware (procedures-require-guard), an
 * `output:` on every procedure (procedure-requires-output), a colocated spec
 * for the service and the router, an audit write reachable from every mutation
 * (mutation-entry-must-reach-audit), and tenantId taken from the request
 * context rather than from the input. The isolation spec is the point of the
 * generator: it asks the tenant-scope extension directly, so the model arrives
 * with a killing case for the isolation canary on day one.
 */
import type { IModuleNames, IPolicy } from './module-plan';

