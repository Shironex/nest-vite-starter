export function repository(n: IModuleNames): string {
  return `import { Injectable } from '@nestjs/common';
import { BaseRepository } from '../../common/database/base.repository';
import { PrismaService } from '../../common/database/prisma.service';

const ${n.screaming}_SELECT = { id: true, name: true, createdAt: true, updatedAt: true } as const;

export interface I${n.model}Record {
  readonly id: string;
  readonly name: string;
  readonly createdAt: Date;
  readonly updatedAt: Date;
}

/**
 * ${n.model} persistence. Every query goes through \`this.client\`, the
 * tenant-scope-extended client, which injects the caller's tenantId into each
 * read and write and fails closed when there is none. That is why no \`where\`
 * here names a tenant: a row of another organization is simply not found.
 */
@Injectable()
export class ${n.model}Repository extends BaseRepository {
  /*
   * Redeclared even though it only forwards: a subclass with no constructor of
   * its own emits no \`design:paramtypes\`, so Nest would construct it with no
   * arguments and \`this.prisma\` would be undefined on the first read.
   */
  constructor(prisma: PrismaService) {
    super(prisma);
  }

  list(): Promise<I${n.model}Record[]> {
    return this.client.${n.accessor}.findMany({
      select: ${n.screaming}_SELECT,
      orderBy: { createdAt: 'desc' },
    });
  }

  findById(id: string): Promise<I${n.model}Record | null> {
    return this.client.${n.accessor}.findUnique({ where: { id }, select: ${n.screaming}_SELECT });
  }

  create(data: { tenantId: string; name: string }): Promise<I${n.model}Record> {
    return this.client.${n.accessor}.create({ data, select: ${n.screaming}_SELECT });
  }

  update(id: string, data: { name: string }): Promise<I${n.model}Record> {
    return this.client.${n.accessor}.update({ where: { id }, data, select: ${n.screaming}_SELECT });
  }
}
`;
}

export function service(n: IModuleNames): string {
  return `import { Injectable } from '@nestjs/common';
import { AUDIT_ACTIONS } from '@repo/shared/audit';
import { AppErrorCode } from '@repo/shared/errors';
import type {
  ${n.model}CreateInput,
  ${n.model}GetInput,
  ${n.model}ListOutput,
  ${n.model}Output,
  ${n.model}UpdateInput,
} from '@repo/shared/schemas';
import { AuditService } from '../audit/audit.service';
import { NotFoundError } from '../../common/errors/domain-error';
import { requireTenantId } from '../../common/context/require-tenant-id';
import { ${n.model}Repository } from './${n.kebab}.repository';
import type { I${n.model}Record } from './${n.kebab}.repository';

/**
 * ${n.model} records of the caller's organization.
 *
 * The tenant comes from the request context and nowhere else: create takes it
 * from \`requireTenantId()\`, and every read and update is scoped by the
 * extension, so another organization's id resolves to NOT_FOUND, never FORBIDDEN (a
 * FORBIDDEN would confirm the row exists).
 */
@Injectable()
export class ${n.model}Service {
  constructor(
    private readonly repository: ${n.model}Repository,
    private readonly auditService: AuditService,
  ) {}

  async list(): Promise<${n.model}ListOutput> {
    const rows = await this.repository.list();
    return { items: rows.map((row) => ${n.model}Service.toOutput(row)) };
  }

  async get(input: ${n.model}GetInput): Promise<${n.model}Output> {
    return ${n.model}Service.toOutput(await this.require(input.id));
  }

  async create(input: ${n.model}CreateInput): Promise<${n.model}Output> {
    const row = await this.repository.create({ tenantId: requireTenantId(), name: input.name });
    await this.auditService.log({
      action: AUDIT_ACTIONS.${n.screaming}_CREATED,
      targetType: '${n.model}',
      targetId: row.id,
    });
    return ${n.model}Service.toOutput(row);
  }

  async update(input: ${n.model}UpdateInput): Promise<${n.model}Output> {
    await this.require(input.id);
    const row = await this.repository.update(input.id, { name: input.name });
    await this.auditService.log({
      action: AUDIT_ACTIONS.${n.screaming}_UPDATED,
      targetType: '${n.model}',
      targetId: row.id,
      metadata: { fields: ['name'] },
    });
    return ${n.model}Service.toOutput(row);
  }

  private async require(id: string): Promise<I${n.model}Record> {
    const row = await this.repository.findById(id);
    if (!row) {
      throw new NotFoundError(AppErrorCode.NOT_FOUND, '${n.model} not found.');
    }
    return row;
  }

  private static toOutput(row: I${n.model}Record): ${n.model}Output {
    return {
      id: row.id,
      name: row.name,
      createdAt: row.createdAt.toISOString(),
      updatedAt: row.updatedAt.toISOString(),
    };
  }
}
`;
}

export function serviceSpec(n: IModuleNames): string {
  return `import { AUDIT_ACTIONS } from '@repo/shared/audit';
import { requestContext } from '../../common/context/request-context';
import { NotFoundError } from '../../common/errors/domain-error';
import { ${n.model}Service } from './${n.kebab}.service';

type Deps = ConstructorParameters<typeof ${n.model}Service>;

const ROW = {
  id: 'row-1',
  name: 'Pierwszy',
  createdAt: new Date('2026-01-02T10:00:00.000Z'),
  updatedAt: new Date('2026-01-02T10:00:00.000Z'),
};

const build = () => {
  const repository = {
    list: jest.fn().mockResolvedValue([ROW]),
    findById: jest.fn().mockResolvedValue(ROW),
    create: jest.fn().mockResolvedValue(ROW),
    update: jest.fn().mockResolvedValue({ ...ROW, name: 'Drugi' }),
  };
  const audit = { log: jest.fn().mockResolvedValue(undefined) };
  const service = new ${n.model}Service(
    repository as unknown as Deps[0],
    audit as unknown as Deps[1],
  );
  return { service, repository, audit };
};

const inTenant = <T>(fn: () => Promise<T>): Promise<T> =>
  requestContext.run({ requestId: '${n.dir}-spec', tenantId: 'tenant-a' }, fn);

describe('${n.model}Service', () => {
  it('lists rows as wire output', async () => {
    const { service } = build();
    await expect(service.list()).resolves.toEqual({
      items: [{ id: 'row-1', name: 'Pierwszy', createdAt: '2026-01-02T10:00:00.000Z', updatedAt: '2026-01-02T10:00:00.000Z' }],
    });
  });

  it('refuses a missing row with NOT_FOUND', async () => {
    const { service, repository } = build();
    repository.findById.mockResolvedValue(null);
    await expect(service.get({ id: 'nope' })).rejects.toBeInstanceOf(NotFoundError);
  });

  it('creates under the tenant from the request context and audits it', async () => {
    const { service, repository, audit } = build();
    await inTenant(() => service.create({ name: 'Pierwszy' }));
    expect(repository.create).toHaveBeenCalledWith({ tenantId: 'tenant-a', name: 'Pierwszy' });
    expect(audit.log).toHaveBeenCalledWith(
      expect.objectContaining({ action: AUDIT_ACTIONS.${n.screaming}_CREATED, targetId: 'row-1' }),
    );
  });

  it('updates an existing row and audits the field names', async () => {
    const { service, repository, audit } = build();
    await expect(service.update({ id: 'row-1', name: 'Drugi' })).resolves.toMatchObject({
      name: 'Drugi',
    });
    expect(repository.update).toHaveBeenCalledWith('row-1', { name: 'Drugi' });
    expect(audit.log).toHaveBeenCalledWith(
      expect.objectContaining({ action: AUDIT_ACTIONS.${n.screaming}_UPDATED, metadata: { fields: ['name'] } }),
    );
  });

  it('does not update or audit a row it cannot see', async () => {
    const { service, repository, audit } = build();
    repository.findById.mockResolvedValue(null);
    await expect(service.update({ id: 'nope', name: 'x' })).rejects.toBeInstanceOf(NotFoundError);
    expect(repository.update).not.toHaveBeenCalled();
    expect(audit.log).not.toHaveBeenCalled();
  });
});
`;
}

export function router(n: IModuleNames, policy: IPolicy): string {
  const writeImports = policy.writeMiddlewares.includes('AdminMiddleware')
    ? "import { AdminMiddleware } from '../auth/middleware/role.middleware';\n"
    : '';
  const writes = policy.writeMiddlewares.join(', ');
  return `import { Router, Query, Mutation, Input, UseMiddlewares } from 'nestjs-trpc';
import type { z } from 'zod';
import {
  ${n.accessor}CreateInput,
  ${n.accessor}GetInput,
  ${n.accessor}ListOutput,
  ${n.accessor}Output,
  ${n.accessor}UpdateInput,
} from '@repo/shared/schemas';
import { AuthMiddleware } from '../auth/middleware/auth.middleware';
${writeImports}import { ${n.model}Service } from './${n.kebab}.service';

/**
 * \`${n.alias}.*\`, policy \`${policy.id}\`: ${policy.summary}
 *
 * Class-level AuthMiddleware gates every procedure; the write middleware set
 * comes from the policy table in tools/generators/module-plan.ts, never from a
 * guess.
 */
@Router({ alias: '${n.alias}' })
@UseMiddlewares(AuthMiddleware)
export class ${n.routerClass} {
  constructor(private readonly ${n.accessor}Service: ${n.model}Service) {}

  @Query({ output: ${n.accessor}ListOutput })
  async list() {
    return this.${n.accessor}Service.list();
  }

  @Query({ input: ${n.accessor}GetInput, output: ${n.accessor}Output })
  async get(@Input() input: z.infer<typeof ${n.accessor}GetInput>) {
    return this.${n.accessor}Service.get(input);
  }

  @Mutation({ input: ${n.accessor}CreateInput, output: ${n.accessor}Output })
  @UseMiddlewares(${writes})
  async create(@Input() input: z.infer<typeof ${n.accessor}CreateInput>) {
    return this.${n.accessor}Service.create(input);
  }

  @Mutation({ input: ${n.accessor}UpdateInput, output: ${n.accessor}Output })
  @UseMiddlewares(${writes})
  async update(@Input() input: z.infer<typeof ${n.accessor}UpdateInput>) {
    return this.${n.accessor}Service.update(input);
  }
}
`;
}

