import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';

import type { IMetaContext, IMetaRule, IViolation } from '../../types';

/*
 * A renamed folder must not drop out of type checking in silence.
 *
 * `include` is a set of patterns, so tsc says nothing about an entry that
 * matches nothing: the folder simply stops being checked, and every error in it
 * disappears from a green run. Only literal entries can be checked this way;
 * a glob matches zero-or-more files by design, and a hidden directory
 * (`.astro/types.d.ts`, `.storybook`) is generated by a tool that has not
 * necessarily run yet, so both are skipped rather than guessed at.
 */
const TSCONFIG = /^tsconfig(?:\..+)?\.json$/u;

const SKIP_DIRS = new Set(['node_modules', 'dist', '.turbo', 'coverage']);

/** Glob metacharacters. An entry carrying one is a pattern, not a path. */
const GLOB = /[*?]/u;

/** JSONC: tsconfig files carry `//` comments, which JSON.parse rejects. */
function stripComments(source: string): string {
  return source.replace(/\/\*[\s\S]*?\*\//gu, '').replace(/(^|[^:'"\\])\/\/.*$/gmu, '$1');
}

function findTsconfigs(dir: string, out: string[]): void {
  let entries: string[];
  try {
    entries = readdirSync(dir);
  } catch {
    return;
  }

  for (const entry of entries) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) {
      if (!SKIP_DIRS.has(entry) && !entry.startsWith('.')) {
        findTsconfigs(full, out);
      }
      continue;
    }
    if (TSCONFIG.test(entry)) {
      out.push(full);
    }
  }
}

/** The literal `include` entries of one tsconfig, or [] when it has none or does not parse. */
export function literalIncludes(source: string): string[] {
  let parsed: unknown;
  try {
    parsed = JSON.parse(stripComments(source));
  } catch {
    return [];
  }

  const include = (parsed as { include?: unknown }).include;
  if (!Array.isArray(include)) {
    return [];
  }

  return include.filter(
    (entry): entry is string =>
      typeof entry === 'string' &&
      entry !== '' &&
      !GLOB.test(entry) &&
      // A hidden directory anywhere in the path: generated by a tool that has
      // not necessarily run in this checkout.
      !entry.split('/').some((segment) => segment.startsWith('.')),
  );
}

export function checkTsconfigIncludePathsExist(root: string): IViolation[] {
  const files: string[] = [];
  findTsconfigs(root, files);

  const violations: IViolation[] = [];

  for (const file of files.sort()) {
    const display = relative(root, file).split(sep).join('/');
    const configDir = dirname(file);

    for (const entry of literalIncludes(readFileSync(file, 'utf8'))) {
      if (existsSync(join(configDir, entry))) {
        continue;
      }
      violations.push({
        file: display,
        rule: 'tsconfig-include-paths-exist',
        message: `\`include\` names \`${entry}\`, which does not exist relative to this config. tsc reports nothing for an entry that matches nothing, so the folder has silently stopped being type checked. Point the entry at where the code moved, or drop it.`,
      });
    }
  }

  return violations;
}

/** Literal (non-glob, non-hidden) tsconfig `include` entries must exist on disk. */
export const tsconfigIncludePathsExistRule: IMetaRule = {
  id: 'tsconfig-include-paths-exist',
  category: 'config',
  ciCritical: true,
  description:
    'Literal paths in a tsconfig `include` must exist on disk, so a renamed folder cannot silently drop out of type checking.',
  run({ root }: IMetaContext): IViolation[] {
    return checkTsconfigIncludePathsExist(root);
  },
};
